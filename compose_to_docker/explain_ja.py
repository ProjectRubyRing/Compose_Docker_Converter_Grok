def analogy_for(service: Service) -> str:
    name = service.name.lower()
    image = (service.image or "").lower()
    if name == "front":
        return "お客さんが最初に話すカウンターです。奥の台所とは、橋の上の名前 back で話します。"
    if name == "back":
        return "カウンターの奥の台所です。冷蔵庫とメモ用紙の準備ができてから開店します。"
    if "jaeger" in name or "jaegertracing" in image:
        return "観察ノートを絵にして廊下に貼る掲示板です。本番の X-Ray の代わりに、このマシンの中で見ます。"
    if "collector" in name or "adot" in name or "aws-otel-collector" in image:
        return "各店から渡される観察メモを受け取り、掲示板へ届ける係です。"
    if any(word in name for word in ("mysql", "aurora", "postgres", "mariadb")) or any(
        word in image for word in ("mysql", "postgres", "mariadb")
    ):
        return "閉めなくても中身が残る冷蔵庫です。データは名前付きボリュームというロッカーに置きます。"
    if "valkey" in name or "redis" in name or "valkey" in image or "/redis" in image:
        if service.volumes:
            return "短い時間だけ覚えておくメモ用紙です。中身はボリュームに残します。"
        return "短い時間だけ覚えておくメモ用紙です。この定義ではロッカーを付けていないので、コンテナを捨てるとメモは消えます。"
    if "localstack" in name or "localstack" in image:
        return "校内に置いた仮の郵便箱です。本番の SQS の代わりに、キューのやり取りをこのマシンの中で練習します。"
    if "lambda" in name:
        return "郵便箱を見に行き、案内係を通して台所へ伝える係です。"
    if name == "alb" or name.endswith("-alb"):
        return "正門の案内係です。経路の先頭に応じて、帳票の部屋、台所、カウンターへ通します。"
    if "batch" in name:
        return "時間になると店を一巡する係です。profile が付いているため、通常の開店では呼びません。"
    if "report" in name:
        return "帳票を作る別室です。観察ノートには自分からは書きません。"
    if "slb" in name or name.startswith("external"):
        return "学校の外にある窓口の代わりです。この定義では中身は同じ種類の小さな受け答え役です。"
    ports = "、".join(service.ports) if service.ports else "外へ開いた扉はありません"
    return f"イメージ {service.image} で動く係です。扉は {ports}。"


def meaning_of_env(key: str, file_note: str) -> str:
    if file_note:
        first = file_note.strip().splitlines()[0]
        return first
    known = {
        "TZ": "コンテナの中で日付を表示するときの時間帯です。",
        "MYSQL_ROOT_PASSWORD": "MySQL が初回起動のときだけ使う、管理者のパスワードです。",
        "MYSQL_DATABASE": "MySQL が初回起動のときに作るデータベースの名前です。",
        "MYSQL_USER": "MySQL が初回起動のときに作る利用ユーザーです。",
        "MYSQL_PASSWORD": "その利用ユーザーのパスワードです。",
        "SERVICES": "LocalStack に、どの AWS の真似をさせるかの一覧です。",
    }
    if key in known:
        return known[key]
    if key.startswith("MYSQL_"):
        return "MySQL 公式イメージの起動プログラムが読む設定です。"
    if key.startswith("AWS_"):
        return "AWS の SDK やコレクターが、地域や資格情報として読む値です。ローカルの練習用です。"
    if key.startswith("OTEL_") or key.startswith("APP_"):
        return "アプリまたは起動スクリプトが、計装と名前の規則を決めるために読む値です。"
    if key.startswith("EAP_") or key.startswith("JVM_") or key.startswith("JAVA_"):
        return "JBoss EAP または JVM の起動方法を変える値です。イメージを作り直さずに切り替えられます。"
    if key.startswith("PEER_") or key.startswith("DB_") or key.startswith("VALKEY_") or key.startswith("SQS_"):
        return "接続先のホスト名、ポート、表示名を渡す値です。"
    if "PASSWORD" in key or "SECRET" in key:
        return "秘密に近い値です。ログや画面共有に残さないでください。"
    return "コンテナの中のプロセスが、この名前で読む設定値です。"


